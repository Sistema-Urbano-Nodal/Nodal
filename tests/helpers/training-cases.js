import assert from 'node:assert/strict';

// Exercise the same public adapter contract against SQLite and the production RPCs.
export async function trainingCases({store,member,course,legacySeat,moveDate,erase}) {
  const early='2026-11-28T12:00:00Z', annual='2027-06-15T16:00:00Z', end='2028-01-01T05:00:00Z';
  const [founder,free,other]=await Promise.all([member(),member(),member()]);
  const config={kind:'course',includedEligible:true,regularCents:10003,promoCents:9500,capacity:5};
  const offer=async (options={})=>{const id=await course();await store.upsertOffering(id,{...config,...options});return id;};
  const rejected=(promise,code)=>assert.rejects(promise,err=>err.code===code);
  const historic=await course('2026');
  await rejected(store.upsertOffering(historic,config),'training_invalid');
  assert.equal((await store.getState(free,historic,early)).offering,null);
  assert.equal((await store.setMemberTerm(founder,'active',early)).active,true);
  assert.equal((await store.getTerm(founder,'2026-11-27')).active,false);
  const first=await offer(), second=await offer(), master=await offer({kind:'masterclass'});
  await rejected(store.reserve(free,first,'included',early),'training_term_inactive');
  const race=await Promise.allSettled([first,second].map(id=>store.reserve(founder,id,'included',early)));
  assert.equal(race.filter(x=>x.status==='fulfilled').length,1);
  assert.equal(race.find(x=>x.status==='rejected').reason.code,'training_quota_used');
  const winner=race.find(x=>x.status==='fulfilled').value;
  assert.equal(winner.term.phase,'early');assert.equal(winner.enrolled,true);assert.equal(winner.canAccess,true);
  const usedCourse=winner.offering.courseId;
  assert.equal((await store.reserve(founder,usedCourse,'included',early)).reservation.id,winner.reservation.id);
  await store.reserve(founder,master,'included',early);
  assert.deepEqual((await store.listState(founder,annual)).used,{course:1,masterclass:1});
  await store.setMemberTerm(founder,'suspended',annual);
  assert.equal((await store.getState(founder,usedCourse,annual)).canAccess,false);
  await store.setMemberTerm(founder,'active',annual);
  assert.equal((await store.getState(founder,usedCourse,annual)).canAccess,true);
  assert.equal((await store.getState(founder,usedCourse,end)).canAccess,false);
  const paid=await offer({includedEligible:false,capacity:1});
  assert.equal((await store.getState(founder,paid,early)).quoteCents,8002);
  assert.equal((await store.getState(free,paid,early)).quoteCents,9500);
  await rejected(store.reserve(founder,paid,'included',early),'training_ineligible');
  await rejected(store.reserve(founder,paid,'additional',end,8002),'training_closed');
  await rejected(store.reserve(founder,paid,'additional',early,9000),'training_price_changed');
  const lastSeat=await Promise.allSettled([free,other].map(id=>store.reserve(id,paid,'additional',early,9500)));
  assert.equal(lastSeat.filter(x=>x.status==='fulfilled').length,1);assert.equal(lastSeat.find(x=>x.status==='rejected').reason.code,'training_full');
  const held=lastSeat.find(x=>x.status==='fulfilled').value;
  assert.equal(held.canAccess,false);assert.equal(held.enrolled,false);assert.equal(held.offering.available,0);
  const old=held.reservation;
  await store.cancelAdditional(old.userId,paid,old.id,early);
  await store.cancelAdditional(old.userId,paid,old.id,early);
  const again=await store.reserve(founder,paid,'additional',early,8002);
  assert.notEqual(again.reservation.id,old.id);
  await rejected(store.cancelAdditional(founder,paid,old.id,early),'training_reserved');
  await rejected(store.confirmAdditional(founder,paid,old.id,early,8002),'training_reserved');
  await rejected(store.confirmAdditional(founder,paid,again.reservation.id,early,9500),'training_price_changed');
  await store.upsertOffering(paid,{...config,promoCents:5000,capacity:1});
  const due=(await store.listPending(paid))[0];assert.equal(due.priceCents,8002);
  const settled=await store.confirmAdditional(founder,paid,due.id,early,8002);
  assert.equal(settled.canAccess,true);assert.equal(settled.enrolled,true);
  assert.equal((await store.confirmAdditional(founder,paid,due.id,early,8002)).reservation.id,due.id);
  assert.equal((await store.getState(founder,paid,end)).canAccess,true,'separately paid enrollment survives annual expiry');
  assert.deepEqual(await store.listPending(paid),[]);
  const promo=await offer({promoCents:5501});assert.equal((await store.getState(founder,promo,early)).quoteCents,5501);
  const existing=await course();await legacySeat(free,existing);await store.upsertOffering(existing,{...config,capacity:1});
  assert.equal((await store.getState(free,existing,early)).canAccess,true);
  assert.equal((await store.getState(other,existing,early)).offering.available,0);
  await rejected(store.reserve(free,existing,'additional',early,9500),'training_already_enrolled');
  await assert.rejects(legacySeat(other,existing),/training_reservation_required/);
  await moveDate(promo,'2026');assert.equal((await store.getState(free,promo,early)).offering.open,false);
  const exp=await store.exportMember(founder,annual);
  assert.equal(exp.reservations.length,3);assert.ok(exp.reservations.every(r=>r.userId===founder));
  const noCost=await offer({promoCents:0});
  assert.equal((await store.getState(founder,noCost,annual)).canInclude,false);
  await rejected(store.reserve(founder,noCost,'included',annual),'training_free_offering');
  const zero=await store.reserve(free,noCost,'additional',annual,0);
  assert.equal(zero.canAccess,true);assert.equal(zero.reservation.status,'enrolled');assert.equal(zero.used.course,0);
  const heldByFree=await offer({capacity:1});
  await store.reserve(free,heldByFree,'additional',early,9500);
  await store.setMemberTerm(free,'active',early);
  await erase(free);
  assert.equal((await store.getTerm(free,annual)).active,false);
  assert.deepEqual((await store.exportMember(free,annual)).reservations,[]);
  assert.equal((await store.getState(other,heldByFree,annual)).offering.available,1);
}
