/* Builds the coastline the globe draws.

   Source: Natural Earth 1:110m land polygons — public domain, no attribution
   required (naturalearthdata.com/about/terms-of-use). Run this only when the
   coastline needs regenerating; the output is committed so the app never
   fetches anything at runtime.

     node scripts/build-coastline.js

   It simplifies with Douglas–Peucker and drops islands too small to read at
   globe scale. The result is written as a compact string that globe.js expands
   at load. */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson';
const OUT = path.resolve(import.meta.dirname, '..', 'web', 'scripts', 'coastline.js');

/* A 500px sphere resolves about 0.36° per pixel at its centre, so half a pixel
   is 0.18°: simplifying any harder than that is visible as angular coastline,
   and any softer is detail nobody can see. */
const TOLERANCE = 0.18;
const MIN_SPAN = 0.8;     // degrees — below this an island is smaller than a node dot
const PRECISION = 1;      // 0.1° is 0.28px on a 500px sphere — under the stroke width

/* perpendicular distance from p to the segment a-b, in degrees */
function far(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

/* iterative Douglas–Peucker: some 50m rings are long enough that recursion
   would overflow the stack */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = 1;
  keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [lo, hi] = stack.pop();
    let worst = 0;
    let index = -1;
    for (let i = lo + 1; i < hi; i += 1) {
      const d = far(points[i], points[lo], points[hi]);
      if (d > worst) { worst = d; index = i; }
    }
    if (index >= 0 && worst > tolerance) {
      keep[index] = 1;
      stack.push([lo, index], [index, hi]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const span = (ring) => {
  const lons = ring.map((p) => p[0]);
  const lats = ring.map((p) => p[1]);
  return Math.max(Math.max(...lons) - Math.min(...lons), Math.max(...lats) - Math.min(...lats));
};

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`could not read Natural Earth land: ${res.status}`);
const geo = await res.json();

const rings = [];
for (const feature of geo.features) {
  const polygons = feature.geometry.type === 'Polygon'
    ? [feature.geometry.coordinates]
    : feature.geometry.coordinates;
  for (const polygon of polygons) {
    const outer = polygon[0];               // exterior ring; lakes are invisible at this scale
    if (span(outer) < MIN_SPAN) continue;
    const thin = simplify(outer, TOLERANCE);
    if (thin.length < 4) continue;
    rings.push(thin);
  }
}

rings.sort((a, b) => b.length - a.length);

/* Each ring is "lon,lat lon,lat ...", rings joined by ";". Plain text so a
   reader can see what it is; it gzips to a few kilobytes. */
const encoded = rings
  .map((ring) => ring
    .map(([lon, lat]) => `${lon.toFixed(PRECISION)},${lat.toFixed(PRECISION)}`)
    .join(' '))
  .join(';');

const points = rings.reduce((n, r) => n + r.length, 0);
const file = `/* World coastline for the globe, generated by scripts/build-coastline.js.
   Source: Natural Earth 1:110m land (public domain). Do not hand-edit —
   regenerate instead. ${rings.length} rings, ${points} points, simplified to
   ${TOLERANCE}° and rounded to ${PRECISION} decimal. */
window.NODAL_COASTLINE = '${encoded}';
`;

await writeFile(OUT, file, 'utf8');
console.log(`coastline: ${rings.length} rings, ${points} points, ${(file.length / 1024).toFixed(1)} KB`);
