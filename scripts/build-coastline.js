/* Builds the coastline the globe draws.

   Source: Natural Earth 1:50m land polygons — public domain, no attribution
   required (naturalearthdata.com/about/terms-of-use). Run this only when the
   coastline needs regenerating; the output is committed so the app never
   fetches anything at runtime.

     node scripts/build-coastline.js

   It simplifies with Douglas–Peucker and drops islands too small to read at
   globe scale. The result is written as a compact string that globe.js expands
   at load. */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson';
const OUT = path.resolve(import.meta.dirname, '..', 'web', 'scripts', 'coastline.js');

/* A 500px sphere resolves about 0.36° per pixel at its centre. Half a pixel is
   0.18°, which was enough while land was an outline — but a filled coastline
   shows its corners, so this simplifies to a quarter of that instead. */
const TOLERANCE = 0.08;
/* Below this an island is smaller than the dot that would mark a city on it.
   The old 0.8° threshold deleted most of the Caribbean, the Greek islands and
   much of Indonesia — real places where NODAL may well have members. */
const MIN_SPAN = 0.15;
/* 2 decimals is a 1.1km grid. At 1 decimal the grid is 11km — coarser than
   TOLERANCE, so rounding would undo the simplification it is meant to preserve. */
const PRECISION = 2;

/* perpendicular distance from p to the segment a-b, in degrees */
function far(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

/* iterative Douglas–Peucker: some 50m rings are long enough that recursion
   would overflow the stack */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = 1;
  keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [lo, hi] = stack.pop();
    let worst = 0;
    let index = -1;
    for (let i = lo + 1; i < hi; i += 1) {
      const d = far(points[i], points[lo], points[hi]);
      if (d > worst) { worst = d; index = i; }
    }
    if (index >= 0 && worst > tolerance) {
      keep[index] = 1;
      stack.push([lo, index], [index, hi]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const span = (ring) => {
  const lons = ring.map((p) => p[0]);
  const lats = ring.map((p) => p[1]);
  return Math.max(Math.max(...lons) - Math.min(...lons), Math.max(...lats) - Math.min(...lats));
};

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`could not read Natural Earth land: ${res.status}`);
const geo = await res.json();

/* A polygon is its outer ring followed by any lakes big enough to read. Lakes
   matter for a filled globe: without them the Caspian and the Great Lakes are
   painted as land. */
const polygons = [];
for (const feature of geo.features) {
  const shapes = feature.geometry.type === 'Polygon'
    ? [feature.geometry.coordinates]
    : feature.geometry.coordinates;
  for (const shape of shapes) {
    const [outerRaw, ...holesRaw] = shape;
    if (span(outerRaw) < MIN_SPAN) continue;
    const outer = simplify(outerRaw, TOLERANCE);
    if (outer.length < 4) continue;
    const holes = holesRaw
      .filter((hole) => span(hole) >= MIN_SPAN)
      .map((hole) => simplify(hole, TOLERANCE))
      .filter((hole) => hole.length >= 4);
    polygons.push([outer, ...holes]);
  }
}

polygons.sort((a, b) => b[0].length - a[0].length);

/* Rings are "lon,lat lon,lat ...". Rings within one polygon are joined by "|",
   the first being its outer boundary; polygons are joined by ";". Plain text so
   a reader can see what it is; it gzips to a few tens of kilobytes. */
const encoded = polygons
  .map((rings) => rings
    .map((ring) => ring
      .map(([lon, lat]) => `${lon.toFixed(PRECISION)},${lat.toFixed(PRECISION)}`)
      .join(' '))
    .join('|'))
  .join(';');

const ringCount = polygons.reduce((n, p) => n + p.length, 0);
const points = polygons.reduce((n, p) => n + p.reduce((m, r) => m + r.length, 0), 0);
const file = `/* World coastline for the globe, generated by scripts/build-coastline.js.
   Source: Natural Earth 1:50m land (public domain). Do not hand-edit —
   regenerate instead. ${polygons.length} polygons, ${ringCount} rings,
   ${points} points, simplified to ${TOLERANCE}° and rounded to ${PRECISION}
   decimals. Rings within a polygon are separated by "|", the first is the
   outer boundary and the rest are lakes. */
window.NODAL_COASTLINE = '${encoded}';
`;

await writeFile(OUT, file, 'utf8');
console.log(`coastline: ${polygons.length} polygons, ${points} points, ${(file.length / 1024).toFixed(1)} KB`);
